fun main() {
    val anInt = 42
    val aDouble = 3.14
    val aFloat = 2.5f
    val aLong = 10000000000L
    val aString = "Hello"
    val aChar = 'K'
    val aBoolean = true

    println("anInt = $anInt")
    println("aDouble = $aDouble")
    println("aFloat = $aFloat")
    println("aLong = $aLong")
    println("aString = $aString")
    println("aChar = $aChar")
    println("aBoolean = $aBoolean")
}
